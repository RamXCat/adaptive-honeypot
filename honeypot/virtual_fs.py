    def resolve_path(self, path: str) -> str:
        """Resolves relative and tilde paths to an absolute virtual path."""
        p = path.strip()
        if p.startswith("~"):
            p = p.replace("~", f"/home/{self.username}", 1)
        if not p.startswith("/"):
            p = os.path.normpath(os.path.join(self.cwd, p)).replace("\\", "/")
        return os.path.normpath(p).replace("\\", "/")

    def set_artifact(self, path: str, content: str) -> None:
        """Stores a dynamically generated artifact into the virtual filesystem."""
        abs_path = self.resolve_path(path)
        # Ensure parent directory exists in virtual dirs
        parent = os.path.dirname(abs_path).replace("\\", "/")
        if parent:
            self.directories.add(parent)
        self.files[abs_path] = content

    def get_artifact(self, path: str) -> str | None:
        abs_path = self.resolve_path(path)
        return self.files.get(abs_path)

